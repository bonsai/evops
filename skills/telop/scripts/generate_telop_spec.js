#!/usr/bin/env node
// generate_telop_spec.js — episode.json から telop_spec.json を生成
// Usage: node scripts/generate_telop_spec.js --episode episode.json --output telop_spec.json

import { program } from 'commander';
import fs from 'fs';
import path from 'path';

program
  .requiredOption('--episode <path>', 'episode.json (from sf-paper-comic)')
  .option('--output <path>', 'Output telop_spec.json', 'telop_spec.json')
  .option('--title <string>', 'Video title')
  .option('--paper-id <string>', 'Paper ID')
  .option('--credits <strings...>', 'Credits array', ['Generated by evops'])
  .option('--lang <code>', 'Subtitle language', 'ja')
  .option('--font <family>', 'Font family', 'IPAexGothic')
  .parse();

const opts = program.opts();

if (!fs.existsSync(opts.episode)) {
  console.error(`Episode not found: ${opts.episode}`);
  process.exit(1);
}

const episode = JSON.parse(fs.readFileSync(opts.episode, 'utf-8'));

const spec = {
  opening: {
    title: opts.title || episode.title || "SF 落語",
    subtitle: opts.paper_id || episode.id || "Paper",
    duration: 3.0,
    font: opts.font,
    color: "#ffffff"
  },
  panels: episode.panels?.map((p, i) => ({
    index: i + 1,
    overlay: p.role || p.text?.substring(0, 20) || `Panel ${i + 1}`,
    duration: 12.0,
    position: "bottom"
  })) || [],
  ending: {
    credits: opts.credits,
    duration: 5.0,
    font: opts.font,
    fade: "both"
  },
  subtitle_track: {
    lang: opts.lang,
    format: "ass",
    segments: episode.panels?.map((p, i) => ({
      start: 4 + i * 12,
      end: 4 + (i + 1) * 12,
      text: p.text || p.role || ""
    })).filter(s => s.text) || []
  },
  watermark: {
    image: "",
    opacity: 0.1,
    position: "bottom-right",
    padding: 10
  }
};

fs.writeFileSync(opts.output, JSON.stringify(spec, null, 2));
console.log(`Generated telop_spec.json: ${opts.output}`);