"""Render a dazzling rotating mirror ball with dancing light specks.

Concept: a perfect mirror sphere surrounded by many small point lights.
As the sphere rotates, reflections of the lights sweep across the facets,
producing a dazzling disco-ball spark effect with bloom.

Usage:
    blender --background --python mirror_ball.py

Outputs (next to this script):
    frames/frame_0001.png ...   rendered frames
    mirror_ball.mp4             H.264 loop
    mirror_ball_manifest.json   machine-readable scene/asset manifest
"""

import json
import math
import os

import numpy as np

import bpy
from mathutils import Vector

HERE = os.path.dirname(os.path.abspath(__file__))
FRAMES_DIR = os.path.join(HERE, "frames")
MP4 = os.path.join(HERE, "mirror_ball.mp4")
GIF = os.path.join(HERE, "mirror_ball.gif")
MANIFEST = os.path.join(HERE, "mirror_ball_manifest.json")

FPS = 24
FRAME_START = 1
FRAME_END = 96
RES_X = 720
RES_Y = 540
BALL_RADIUS = 1.0
LIGHT_RADIUS = 5.8
LIGHT_COUNT = 64
LIGHT_ENERGY = 4000
STAR_SIZE = 2048


def fibonacci_sphere_points(n):
    """Evenly distribute n points on a sphere (Fibonacci lattice)."""
    phi = math.pi * (3.0 - math.sqrt(5.0))
    pts = []
    for i in range(n):
        y = 1.0 - (i / float(n - 1)) * 2.0
        radius = math.sqrt(1.0 - y * y)
        theta = phi * i
        x = math.cos(theta) * radius
        z = math.sin(theta) * radius
        pts.append((x, y, z))
    return pts


def clear_scene():
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete(use_global=False)


def _material(name, mirror, roughness, metallic):
    mat = bpy.data.materials.new(name)
    tree = mat.node_tree
    tree.nodes.clear()
    out = tree.nodes.new("ShaderNodeOutputMaterial")
    out.location = (900, 0)
    base = tree.nodes.new("ShaderNodeBsdfPrincipled")
    base.location = (500, 0)
    base.inputs["Base Color"].default_value = (0.02, 0.02, 0.04, 1.0)
    base.inputs["Metallic"].default_value = metallic
    base.inputs["Roughness"].default_value = roughness
    if mirror > 0.0:
        tree.links.new(base.outputs["BSDF"], out.inputs["Surface"])
    else:
        tree.links.new(base.outputs["BSDF"], out.inputs["Surface"])
    mat.use_nodes = True
    return mat


def create_ball():
    bpy.ops.mesh.primitive_uv_sphere_add(
        segments=128, ring_count=128, radius=BALL_RADIUS
    )
    ball = bpy.context.object
    ball.name = "MirrorBall"
    mat = _material("MirrorBallMat", mirror=0.95, roughness=0.01, metallic=1.0)
    ball.data.materials.append(mat)
    return ball


def _light(name, loc, color=(1, 1, 1), energy=LIGHT_ENERGY):
    bpy.ops.object.light_add(type="POINT", location=tuple(loc))
    light = bpy.context.object
    light.name = name
    light.data.energy = energy
    light.data.color = color
    return light


def create_lights():
    pts = fibonacci_sphere_points(LIGHT_COUNT)
    np.random.seed(0)
    colors = []
    for _ in range(LIGHT_COUNT):
        # warm core + occasional cool highlights
        base = (1.0, 0.95, 0.85)
        if np.random.rand() > 0.8:
            base = (0.85, 0.9, 1.0)
        else:
            base = (1.0, base[0] + np.random.uniform(0.0, 0.06), base[1] + np.random.uniform(0.0, 0.06))
        colors.append(base)
    for i, (pt, col) in enumerate(zip(pts, colors)):
        loc = (pt[0] * LIGHT_RADIUS, pt[1] * LIGHT_RADIUS, pt[2] * LIGHT_RADIUS)
        _light(f"SpecLight_{i:03d}", loc, color=col)


def create_camera():
    bpy.ops.object.camera_add(location=(5.0, -5.5, 3.0))
    camera = bpy.context.object
    camera.name = "Camera"
    target = Vector((0, 0, 0))
    camera.rotation_euler = (target - camera.location).to_track_quat("-Z", "Y").to_euler()
    camera.data.lens = 40
    bpy.context.scene.camera = camera
    return camera


def setup_scene():
    clear_scene()
    ball = create_ball()
    create_lights()
    create_camera()

    scene = bpy.context.scene
    scene.render.engine = "BLENDER_EEVEE"
    scene.render.fps = FPS
    scene.frame_start = FRAME_START
    scene.frame_end = FRAME_END
    scene.render.resolution_x = RES_X
    scene.render.resolution_y = RES_Y
    scene.render.film_transparent = False
    scene.render.image_settings.file_format = "PNG"
    scene.render.filepath = os.path.join(FRAMES_DIR, "frame_")

    # Eevee bloom for the dazzling effect
    try:
        scene.eevee.bloom = True
        scene.eevee.bloom_threshold = 0.8
        scene.eevee.bloom_smoothing = 256
        scene.eevee.bloom_size = 32
        scene.eevee.bloom_quality = 3
    except Exception:
        pass

    # Environment: load the star-field texture (pre-generated by gen_starfield.py)
    # so the mirror reflects bright stars even on the sphere's far side.
    star_path = os.path.join(HERE, "starfield.png")
    star_exists = os.path.exists(star_path)
    if not star_exists:
        print("Warning: starfield.png not found; using dark background")

    if scene.world is None:
        scene.world = bpy.data.worlds.new("World")
    scene.world.use_nodes = True
    tree = scene.world.node_tree
    tree.nodes.clear()
    if star_exists:
        tex = tree.nodes.new("ShaderNodeTexEnvironment")
        tex.image = bpy.data.images.load(star_path)
        bg = tree.nodes.new("ShaderNodeBackground")
        tree.links.new(tex.outputs["Color"], bg.inputs["Color"])
        bg.inputs["Strength"].default_value = 1.0
    else:
        bg = tree.nodes.new("ShaderNodeBackground")
        bg.inputs["Color"].default_value = (0.01, 0.01, 0.02, 1.0)
        bg.inputs["Strength"].default_value = 0.2
    output = tree.nodes.get("Output")
    if output is None:
        output = tree.nodes.new("ShaderNodeOutputWorld")
    tree.links.new(bg.outputs["Background"], output.inputs["Surface"])

    # Animate the ball: one full rotation plus a slight axis wobble
    for frame in range(FRAME_START, FRAME_END + 1):
        t = (frame - FRAME_START) / (FRAME_END - FRAME_START)
        angle = 2.0 * math.pi * t
        ball.rotation_euler = (angle * 1.0, angle * 0.15, angle * 0.3)
        ball.keyframe_insert("rotation_euler", frame=frame)

    scene.render.image_settings.file_format = "PNG"
    scene.render.image_settings.compression = 15
    return scene


def write_manifest():
    manifest = {
        "subject": "mirrorball",
        "fps": FPS,
        "duration_seconds": (FRAME_END - FRAME_START + 1) / FPS,
        "frame_start": FRAME_START,
        "frame_end": FRAME_END,
        "resolution": [RES_X, RES_Y],
        "scene": {"ball": {"radius": BALL_RADIUS}},
        "assets": [
            {"id": "procedural:ball", "source": "blender", "type": "mesh"},
            {"id": "procedural:lights", "source": "blender", "type": "light_array"},
        ],
        "lighting": {
            "count": LIGHT_COUNT,
            "arrangement": "fibonacci_sphere",
            "radius": LIGHT_RADIUS,
            "energy": LIGHT_ENERGY,
            "colors": ["warm", "cool_highlight"],
        },
        "camera": {"location": [5.0, -5.5, 3.0], "lens": 40},
        "render": {
            "engine": "BLENDER_EEVEE",
            "bloom": {"threshold": 0.8, "intensity": 0.5, "quality": 3},
            "output": "frames/frame_%04d.png",
        },
        "motion": [{"target": "MirrorBall", "action": "rotate_360", "frames": [FRAME_START, FRAME_END]}],
    }
    with open(MANIFEST, "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2)
        fh.write("\n")


if __name__ == "__main__":
    os.makedirs(FRAMES_DIR, exist_ok=True)
    setup_scene()
    write_manifest()
    bpy.ops.render.render(animation=True)
    print("FRAMES:", FRAMES_DIR)
    print("MANIFEST:", MANIFEST)
